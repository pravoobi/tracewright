"""Test runs and results API."""
from __future__ import annotations

import re
import uuid
from typing import Any

from fastapi import APIRouter, Depends
from pydantic import BaseModel
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from backend.src.agents.healer import heal_frequency_30d, heal_test
from backend.src.db.models import TestCard, TestResult, TestRun
from backend.src.db.session import get_session
from backend.src.versioning.filtering import is_applicable

router = APIRouter(prefix="/tests", tags=["tests"])

_ANSI_ESCAPE = re.compile(r"\x1b\[[0-9;]*m")
_TEST_ID_PATTERN = re.compile(r"\bTC-[\w-]+\b")

_STATUS_MAP = {
    "passed": "passed",
    "failed": "failed",
    "timedOut": "failed",
    "skipped": "skipped",
    "interrupted": "failed",
}


class IngestRunRequest(BaseModel):
    environment_id: str
    report: dict[str, Any]  # raw Playwright JSON reporter output


def _clean_error(message: str | None) -> str | None:
    if not message:
        return None
    return _ANSI_ESCAPE.sub("", message)


def _extract_test_id(suite_titles: list[str]) -> str | None:
    """Test-card IDs are embedded in the describe-block title generated by
    codegen.py (e.g. "TC-DISCOUNT-001: Discount code application at checkout")."""
    for title in suite_titles:
        match = _TEST_ID_PATTERN.search(title)
        if match:
            return match.group(0)
    return None


def _walk_specs(suites: list[dict[str, Any]], ancestor_titles: list[str] | None = None):
    """Yield (spec, ancestor_titles) for every spec in a Playwright JSON report's suite tree."""
    ancestor_titles = ancestor_titles or []
    for suite in suites:
        titles = ancestor_titles + [suite.get("title", "")]
        for spec in suite.get("specs", []):
            yield spec, titles
        yield from _walk_specs(suite.get("suites", []), titles)


@router.get("/{tenant_id}/applicable")
async def get_applicable_tests(
    tenant_id: str,
    environment_id: str,
    session: AsyncSession = Depends(get_session),
):
    """Return test cards applicable to the given environment, filtered by version."""
    from backend.src.db.models import Environment, TestCard, Tenant
    from sqlalchemy import select

    env_stmt = select(Environment).where(
        Environment.id == uuid.UUID(environment_id),
        Environment.tenant_id == uuid.UUID(tenant_id),
    )
    env_result = await session.execute(env_stmt)
    env = env_result.scalar_one_or_none()
    if not env:
        return {"error": "Environment not found"}

    tenant_stmt = select(Tenant).where(Tenant.id == uuid.UUID(tenant_id))
    tenant_result = await session.execute(tenant_stmt)
    tenant = tenant_result.scalar_one_or_none()
    version_ordering = tenant.version_ordering if tenant else []

    cards_stmt = select(TestCard).where(
        TestCard.tenant_id == uuid.UUID(tenant_id),
        TestCard.approval_status == "approved",
    )
    cards_result = await session.execute(cards_stmt)
    all_cards = cards_result.scalars().all()

    applicable = [
        {
            "id": str(c.id),
            "test_id": c.test_id,
            "title": c.title,
            "playwright_code_path": c.playwright_code_path,
            "setup_manifest": c.setup_manifest,
        }
        for c in all_cards
        if is_applicable(
            card={"introduced_in_version": c.introduced_in_version,
                  "deprecated_in_version": c.deprecated_in_version,
                  "applicability": c.applicability},
            env_code_version=env.code_version,
            env_name=env.name,
            version_ordering=version_ordering,
        )
    ]
    return {"environment": env.name, "applicable_tests": applicable, "count": len(applicable)}


@router.get("/{tenant_id}/runs")
async def list_runs(tenant_id: str, session: AsyncSession = Depends(get_session)):
    stmt = select(TestRun).where(TestRun.tenant_id == uuid.UUID(tenant_id))
    result = await session.execute(stmt)
    runs = result.scalars().all()
    return [
        {
            "id": str(r.id),
            "environment_id": str(r.environment_id),
            "started_at": r.started_at.isoformat() if r.started_at else None,
            "completed_at": r.completed_at.isoformat() if r.completed_at else None,
            "total": r.total_tests,
            "passed": r.passed,
            "failed": r.failed,
            "skipped": r.skipped,
        }
        for r in runs
    ]


@router.post("/{tenant_id}/runs")
async def ingest_run(
    tenant_id: str,
    body: IngestRunRequest,
    session: AsyncSession = Depends(get_session),
):
    """Ingest a Playwright JSON reporter run (test-results/results.json as
    produced by test-scaffold/playwright.config.ts's `json` reporter). Creates
    one TestRun plus one TestResult per spec, matched back to test_cards via
    the TC-XXX id embedded in the generated describe-block title."""
    cards_stmt = select(TestCard).where(TestCard.tenant_id == uuid.UUID(tenant_id))
    cards_result = await session.execute(cards_stmt)
    cards_by_test_id = {c.test_id: c for c in cards_result.scalars().all()}

    run = TestRun(
        tenant_id=uuid.UUID(tenant_id),
        environment_id=uuid.UUID(body.environment_id),
        total_tests=0,
        passed=0,
        failed=0,
        skipped=0,
    )
    session.add(run)
    await session.flush()

    unmatched: list[str] = []
    counts = {"passed": 0, "failed": 0, "skipped": 0}

    for spec, ancestor_titles in _walk_specs(body.report.get("suites", [])):
        test_id = _extract_test_id(ancestor_titles + [spec.get("title", "")])
        card = cards_by_test_id.get(test_id) if test_id else None
        if not card:
            unmatched.append(spec.get("title", "<untitled>"))
            continue

        for test in spec.get("tests", []):
            for res in test.get("results", []):
                status = _STATUS_MAP.get(res.get("status", ""), "failed")
                counts[status] = counts.get(status, 0) + 1
                errors = res.get("errors", [])
                error_message = _clean_error(errors[0].get("message")) if errors else None

                session.add(TestResult(
                    run_id=run.id,
                    test_card_id=card.id,
                    status=status,
                    duration_ms=res.get("duration"),
                    error_message=error_message,
                ))

    run.total_tests = sum(counts.values())
    run.passed = counts["passed"]
    run.failed = counts["failed"]
    run.skipped = counts["skipped"]
    await session.commit()

    return {
        "run_id": str(run.id),
        "total": run.total_tests,
        "passed": run.passed,
        "failed": run.failed,
        "skipped": run.skipped,
        "unmatched_specs": unmatched,
    }


@router.post("/{tenant_id}/results/{result_id}/heal")
async def trigger_heal(
    tenant_id: str,
    result_id: str,
    session: AsyncSession = Depends(get_session),
):
    decision = await heal_test(session, result_id, tenant_id=tenant_id)
    return {
        "test_result_id": decision.test_result_id,
        "failure_type": decision.failure_type,
        "action": decision.action,
        "heal_count_30d": decision.heal_count_30d,
        "detail": decision.detail,
    }


@router.get("/{tenant_id}/heal-stats")
async def heal_stats(tenant_id: str, session: AsyncSession = Depends(get_session)):
    """Heal-frequency dashboard metric: which tests were healed, and how often."""
    stmt = select(TestCard).where(
        TestCard.tenant_id == uuid.UUID(tenant_id),
        TestCard.heal_count > 0,
    )
    result = await session.execute(stmt)
    cards = result.scalars().all()

    stats = []
    for c in cards:
        count_30d = await heal_frequency_30d(session, c.id)
        stats.append({
            "test_id": c.test_id,
            "title": c.title,
            "heal_count_lifetime": c.heal_count,
            "heal_count_30d": count_30d,
            "escalated": count_30d >= 3,
            "approval_status": c.approval_status,
        })
    return {"cards": stats}
