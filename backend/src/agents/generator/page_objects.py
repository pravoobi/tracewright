"""Render the Phase 1 registry as TypeScript page-object classes.

Generated specs import `../page-objects/<Name>` and call its getters, so those
files must come from the same registry whose locators were verified, not be
maintained by hand. Every locator expression here was produced by
find_verified_locator; names are re-validated because a registry can also be
built from caller-supplied flows.
"""
from __future__ import annotations

import json
import os
import re

from backend.src.agents.generator.app_model import AppModelRegistry, PageObject

_CLASS_NAME = re.compile(r"[A-Z][A-Za-z0-9]{0,40}Page")
_MEMBER_NAME = re.compile(r"[a-z][A-Za-z0-9]{0,50}")
_RESERVED = {"page", "goto", "waitForNetworkIdle", "url_pattern", "constructor"}
_LOCATOR = re.compile(r"page\.(getByRole|getByTestId|locator)\(.*\)")


def _describe_reach(steps: list[dict]) -> str:
    parts = []
    for s in steps:
        if s["action"] == "goto":
            parts.append(f"open {s['url']}")
        elif s["action"] == "fill":
            parts.append(f"fill {s.get('name') or s.get('testid')} with {s['value']}")
        else:
            parts.append(f"click {s.get('name') or s.get('testid')}")
    return "; ".join(parts)


def render_page_object(po: PageObject) -> str | None:
    if not _CLASS_NAME.fullmatch(po.name):
        return None
    lines = [
        'import { Page } from "@playwright/test";',
        'import { BasePage } from "./BasePage";',
        "",
        "// Generated by Tracewright from the Phase 1 page-object registry; every locator below",
        "// was verified against the live app. Regenerate instead of editing by hand.",
        f"export class {po.name} extends BasePage {{",
        f"  readonly url_pattern = {json.dumps(po.url_pattern)};",
        "",
        "  constructor(page: Page) {",
        "    super(page);",
        "  }",
    ]
    for name, code in po.locators.items():
        if name in _RESERVED or not _MEMBER_NAME.fullmatch(name) or not _LOCATOR.fullmatch(code):
            continue
        lines.append("")
        reach = po.requires_state.get(name)
        if reach:
            # json.dumps keeps card/LLM-derived text on one line of the comment.
            lines.append(
                "  // Exists only after: " + json.dumps(_describe_reach(reach), ensure_ascii=False)
            )
        lines += [f"  get {name}() {{", f"    return this.{code};", "  }"]
    lines += ["}", ""]
    return "\n".join(lines)


def write_page_objects(registry: AppModelRegistry, out_dir: str) -> list[str]:
    os.makedirs(out_dir, exist_ok=True)
    written = []
    for po in registry.pages.values():
        source = render_page_object(po)
        if source is None:
            continue
        path = os.path.join(out_dir, f"{po.name}.ts")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(source)
        written.append(path)
    return written
